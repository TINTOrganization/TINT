import type { ArchNodeId } from './architecture';

export interface ArchStep {
  from: ArchNodeId;
  /** Igual a `from` en un paso interno (algo que el componente hace sin hablar con nadie). */
  to: ArchNodeId;
  /** Id del conector (C1…C15), o null en un paso interno. */
  connector: string | null;
  /** Pregunta de la pestaña Predecir: describe la intención sin nombrar el destino. */
  ask: string;
  /** Qué viaja. */
  message: string;
  detail: string;
  /** Decisión de arquitectura detrás del paso, si la hay. */
  why?: string;
  sources: string[];
}

export interface ArchStory {
  id: string;
  title: string;
  actor: 'Host' | 'Invitado';
  summary: string;
  steps: ArchStep[];
  /** Preguntas de /test-me relacionadas (ids de quizQuestions). */
  quizIds: string[];
}

